/**
 * Kiest de taal: de eerste taal van de telefoon die het spel heeft, anders de
 * standaardtaal van het spel. `deviceLanguages` zijn codes zoals `es` of `pt-BR`.
 */
export function pickLanguage(deviceLanguages: readonly string[], available: readonly string[], fallback: string): string {
  for (const tag of deviceLanguages) {
    const code = tag.toLowerCase().split(/[-_]/)[0]!;
    if (available.includes(code)) return code;
  }
  return available.includes(fallback) ? fallback : (available[0] ?? fallback);
}

/** Vertaalt een tekst van de app; onbekende talen vallen terug op Engels. */
export function msg(lang: string, key: MessageKey, vars: Record<string, string | number> = {}): string {
  const text = (MESSAGES[lang] ?? MESSAGES.en!)[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

/** Speeltijd als 1:05:09 of 12:34. */
export function formatDuration(ms: number): string {
  const total = Math.max(0, Math.floor(ms / 1000));
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  const pad = (n: number) => String(n).padStart(2, '0');
  return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${m}:${pad(s)}`;
}
