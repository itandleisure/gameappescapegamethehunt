export const LEADER_MESSAGES: Record<string, Dict> = { nl, en, de, es, pt, it };

/** Tekst in de taal van de telefoon; andere talen krijgen Engels. */
export function leaderMsg(lang: string, key: LeaderKey, vars: Record<string, string | number> = {}): string {
  const dict = LEADER_MESSAGES[lang] ?? en;
  return dict[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}
